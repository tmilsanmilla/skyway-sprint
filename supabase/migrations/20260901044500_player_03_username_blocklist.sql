create or replace function public.set_player_username(new_username text)
returns public.player_profiles
language plpgsql
security definer
set search_path = ''
as $$
declare existing public.player_profiles; result public.player_profiles; normalized text;
begin
  if auth.uid() is null then raise exception 'Sign in required'; end if;
  new_username := trim(new_username);
  if new_username !~ '^[A-Za-z0-9_]{3,20}$' then raise exception 'Username must be 3-20 letters, numbers, or underscores'; end if;
  normalized := lower(regexp_replace(new_username, '[^a-zA-Z0-9]', '', 'g'));
  if exists (select 1 from public.username_blocklist where (length(term) < 4 and normalized = term) or (length(term) >= 4 and position(term in normalized) > 0)) then
    raise exception 'That username is not allowed';
  end if;
  select * into existing from public.player_profiles where user_id=auth.uid();
  if found and existing.username_changed_at > now() - interval '30 days' then raise exception 'Username can only be changed once every 30 days'; end if;
  insert into public.player_profiles(user_id,username) values(auth.uid(),new_username)
  on conflict(user_id) do update set username=excluded.username,username_changed_at=now() returning * into result;
  return result;
exception when unique_violation then raise exception 'That username is already taken';
end $$;
revoke all on function public.set_player_username(text) from public;
grant execute on function public.set_player_username(text) to authenticated;

